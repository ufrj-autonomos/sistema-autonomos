import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

async function main() {
  const url = process.env.TEST_DATABASE_URL;
  if (!url || !['localhost', '127.0.0.1', '[::1]'].includes(new URL(url).hostname)) throw new Error('Use somente TEST_DATABASE_URL local e descartável.');
  process.env.DATABASE_URL = url;
  process.env.DIRECT_URL = url;
  process.env.JWT_SECRET = 'isolated-attendance-test-signing-key-at-least-32-characters';
  process.env.NEXT_PUBLIC_APP_URL = 'https://attendance.example.invalid';
  const { prisma } = await import('../src/lib/prisma');
  const { updateAccount } = await import('../src/lib/user-administration');
  const { registerAttendance, manageAttendanceVisit, attendanceReport } = await import('../src/lib/attendance/service');
  const { createUserSession, SESSION_COOKIE_NAME } = await import('../src/lib/session');
  const { inputLabDateTime } = await import('../src/lib/attendance/format');
  const { weekKey, weekRange, overlapSeconds } = await import('../src/lib/attendance/time');
  const { NextRequest } = await import('next/server');
  const ids: string[] = []; const memberIds: number[] = [];
  async function session(user: { id: string; email: string; name: string; role: string }) {
    return createUserSession({ ...user, status: 'APPROVED' });
  }
  try {
    const marker = randomUUID();
    const admin = await prisma.user.create({ data: { name: 'Isolated admin', email: `${marker}-admin@example.invalid`, passwordHash: 'unused', role: 'ADMIN', status: 'APPROVED' } }); ids.push(admin.id);
    const user = await prisma.user.create({ data: { name: 'Isolated member', email: `${marker}-member@example.invalid`, passwordHash: 'unused', role: 'TRAINEE', status: 'PENDING' } }); ids.push(user.id);
    await updateAccount(admin.id, user.id, { status: 'APPROVED' });
    const member = await prisma.member.findUniqueOrThrow({ where: { userId: user.id } }); memberIds.push(member.id);
    assert.equal(await prisma.attendancePeriod.count({ where: { memberId: member.id, endsOn: null } }), 1, 'approval enrolls the member');
    const settings = await prisma.attendanceSettings.findUniqueOrThrow({ where: { id: 'lab' } });
    assert.match(settings.qrCode, /^[a-f0-9]{64}$/);
    await assert.rejects(registerAttendance(user.id, { code: '0'.repeat(64), requestId: randomUUID() }), { status: 403 });
    await assert.rejects(registerAttendance(user.id, { code: settings.qrCode, requestId: randomUUID(), memberId: member.id }), { status: 400 });
    const requestId = randomUUID();
    const first = await registerAttendance(user.id, { code: settings.qrCode, requestId });
    assert.equal(first.action, 'IN'); assert.equal(first.duplicate, false);
    const duplicate = await registerAttendance(user.id, { code: settings.qrCode, requestId });
    assert.equal(duplicate.duplicate, true); assert.equal(duplicate.visit.id, first.visit.id);
    const concurrent = await Promise.all(Array.from({ length: 6 }, () => registerAttendance(user.id, { code: settings.qrCode, requestId: randomUUID() })));
    assert.ok(concurrent.every(punch => punch.action === 'IN' && punch.duplicate));
    assert.equal(await prisma.attendanceVisit.count({ where: { memberId: member.id, status: 'OPEN' } }), 1);
    assert.equal(await prisma.attendancePunch.count({ where: { memberId: member.id } }), 1);
    const now = new Date();
    const start = new Date(now.getTime() - 2 * 3600_000 - 2000);
    await prisma.attendanceVisit.update({ where: { id: first.visit.id }, data: { checkedInAt: start } });
    await prisma.attendancePunch.updateMany({ where: { memberId: member.id }, data: { registeredAt: new Date(now.getTime() - 61_000) } });
    const outId = randomUUID();
    const out = await registerAttendance(user.id, { code: settings.qrCode, requestId: outId });
    assert.equal(out.action, 'OUT'); assert.equal(out.visit.status, 'CLOSED'); assert.ok(out.visit.seconds >= 7200);
    assert.equal((await registerAttendance(user.id, { code: settings.qrCode, requestId: outId })).duplicate, true);
    const ownReport = await attendanceReport(undefined, user.id);
    assert.equal(ownReport.members.length, 1);
    const range = weekRange(weekKey());
    assert.equal(ownReport.members[0].completedSeconds, overlapSeconds(start, new Date(out.registeredAt), range.start, range.end));
    await assert.rejects(manageAttendanceVisit(user.id, { action: 'VOID', visitId: first.visit.id, reason: 'Non admin must not edit' }), { status: 403 });
    await manageAttendanceVisit(admin.id, { action: 'VOID', visitId: first.visit.id, reason: 'Isolated test of audit preservation' });
    assert.equal((await attendanceReport(undefined, user.id)).members[0].completedSeconds, 0);
    assert.equal(await prisma.attendanceAudit.count({ where: { visitId: first.visit.id } }), 1);
    const correctedStart = new Date(now.getTime() - 4 * 3600_000);
    const correctedEnd = new Date(now.getTime() - 2 * 3600_000);
    const corrected = await manageAttendanceVisit(admin.id, { action: 'CORRECT', visitId: first.visit.id, checkedInAt: inputLabDateTime(correctedStart.toISOString()), checkedOutAt: inputLabDateTime(correctedEnd.toISOString()), reason: 'Corrected after reviewing laboratory records' });
    assert.equal(corrected.status, 'CLOSED'); assert.equal(corrected.seconds, 7200);
    await assert.rejects(manageAttendanceVisit(admin.id, { action: 'CREATE', memberId: member.id, checkedInAt: inputLabDateTime(correctedStart.toISOString()), checkedOutAt: inputLabDateTime(correctedEnd.toISOString()), reason: 'Overlapping entry must be rejected' }), { status: 409 });
    const audits = await prisma.attendanceAudit.findMany({ where: { visitId: first.visit.id }, orderBy: { createdAt: 'asc' } });
    assert.equal(audits.length, 2); assert.equal(audits[1].actorId, admin.id); assert.ok(audits[1].before && audits[1].after);
    await prisma.attendancePunch.updateMany({ where: { memberId: member.id }, data: { registeredAt: new Date(now.getTime() - 61_000) } });
    const second = await registerAttendance(user.id, { code: settings.qrCode, requestId: randomUUID() });
    assert.equal(second.action, 'IN');
    await prisma.attendanceVisit.update({ where: { id: second.visit.id }, data: { checkedInAt: new Date(now.getTime() - 13 * 3600_000) } });
    await prisma.attendancePunch.updateMany({ where: { memberId: member.id }, data: { registeredAt: new Date(now.getTime() - 61_000) } });
    const stale = await registerAttendance(user.id, { code: settings.qrCode, requestId: randomUUID() });
    assert.equal(stale.action, 'OUT'); assert.equal(stale.visit.status, 'REVIEW'); assert.equal(stale.visit.seconds, 0);
    const ownToken = await session(user); const adminToken = await session(admin);
    const req = (path: string, token: string) => new NextRequest(`https://attendance.example.invalid${path}`, { headers: { cookie: `${SESSION_COOKIE_NAME}=${token}` } });
    const me = await import('../src/app/api/attendance/me/route');
    const management = await import('../src/app/api/admin/attendance/route');
    const qr = await import('../src/app/api/admin/attendance/qr/route');
    const auditApi = await import('../src/app/api/admin/attendance/visits/[id]/route');
    const personal = await me.GET(req(`/api/attendance/me?userId=${admin.id}`, ownToken));
    assert.equal(personal.status, 200);
    const body = await personal.json(); assert.equal(body.members.length, 1); assert.equal(body.members[0].id, member.id); assert.equal(JSON.stringify(body).includes(settings.qrCode), false);
    assert.equal((await management.GET(req('/api/admin/attendance', ownToken))).status, 403);
    assert.equal((await qr.GET(req('/api/admin/attendance/qr', ownToken))).status, 403);
    const poster = await qr.GET(req('/api/admin/attendance/qr', adminToken));
    assert.equal(poster.status, 200); assert.match((await poster.json()).image, /^data:image\/png;base64,/);
    const auditResponse = await auditApi.GET(req(`/api/admin/attendance/visits/${first.visit.id}`, adminToken), { params: Promise.resolve({ id: first.visit.id }) });
    assert.equal(auditResponse.status, 200); assert.equal((await auditResponse.json()).audits.length, 2);
    await updateAccount(admin.id, user.id, { status: 'SUSPENDED' });
    assert.equal(await prisma.attendancePeriod.count({ where: { memberId: member.id, endsOn: null } }), 0);
    await assert.rejects(registerAttendance(user.id, { code: settings.qrCode, requestId: randomUUID() }), { status: 403 });
    await updateAccount(admin.id, user.id, { status: 'APPROVED' });
    assert.equal(await prisma.attendancePeriod.count({ where: { memberId: member.id, endsOn: null } }), 1);
    await updateAccount(admin.id, user.id, { status: 'REJECTED' });
    assert.equal((await prisma.member.findUniqueOrThrow({ where: { id: member.id } })).userId, null);
    assert.equal(await prisma.attendanceVisit.count({ where: { memberId: member.id } }), 2, 'deleting an account preserves attendance history');
    assert.equal(await prisma.attendanceAudit.count({ where: { memberId: member.id } }), 2);
    console.log('Presença no PostgreSQL: aprovação, QR, concorrência, idempotência, saída, revisão, ajustes, auditoria, privacidade e suspensão passaram.');
  } finally {
    await prisma.user.deleteMany({ where: { id: { in: ids } } });
    await prisma.member.deleteMany({ where: { id: { in: memberIds } } });
    await prisma.$disconnect();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
